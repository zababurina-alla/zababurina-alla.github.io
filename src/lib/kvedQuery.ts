/** Код: «96,02» / «96 02» / «9602» / «96.02» → «96.02»; «452» → «45.2»; «96» и «96.0» — как есть. */
function code(q: string): string | null {
  const m = /^(\d{2})(?:[.,\s]?(\d{1,2}))?$/.exec(q);
  if (!m) return null;
  return m[2] ? `${m[1]}.${m[2]}` : (m[1] ?? q);
}

export function kvedQuery(raw: string): string {
  const q = raw.trim().replace(/\s+/g, ' ');
  const c = code(q);
  if (c) return c;
  const low = q.toLowerCase();
  for (const [ru, uk] of RU_UK) {
    const re = new RegExp(`(^|[^а-яёіїєґ])${ru}[а-яё]*`, 'u');
    if (re.test(low)) return low.replace(re, `$1${uk}`);
  }
  return q;
}
