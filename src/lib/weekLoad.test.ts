import { describe, expect, it } from 'vitest';
import { mondayOf, weekLoad } from './weekLoad';

describe('нагрузка по неделям', () => {
  it('неделя — с понедельника (14.10.2026 — среда)', () => {
    expect(['2026-10-14', '2026-10-12', '2026-10-18', '2026-10-19'].map(mondayOf)).toEqual(['2026-10-12', '2026-10-12', '2026-10-12', '2026-10-19']);
  });
  it('просроченные — отдельно, остальные — по неделям; дальше 6 недель не считаем', () => {
    const r = weekLoad(['2026-10-10', '2026-10-14', '2026-10-18', '2026-10-20', '2026-10-20', '2026-11-20', '2027-01-20'], '2026-10-14');
    expect(r.overdue).toBe(1);
    expect(r.weeks.map((w) => [w.start, w.count])).toEqual([['2026-10-12', 2], ['2026-10-19', 2], ['2026-10-26', 0], ['2026-11-02', 0], ['2026-11-09', 0], ['2026-11-16', 1]]);
  });
});
