import { describe, expect, it } from 'vitest';
import { kvedLookup, kvedMap, normalizeKved } from './kvedLookup';

// Лист «📑 КВЕДы» как на живой: часть кодов — группами и разделами. Названия — условные метки строк листа.
const SHEET = ['42.9', '43.2', '43.3', '42.2', '47.1', '46', '47.54', '47.91', '47.99', '56.10', '96.02', '01.11', '62.01']
  .map((code) => ({ code, title: `строка ${code}` }));
const map = kvedMap(SHEET, (r) => r.code);

// Корпус координатора (16.10) + коды с нулём в конце, пробелами и без точки. Новый промах — сюда.
const CORPUS: [string, string | null][] = [
  ['42.99', '42.9'], ['43.21', '43.2'], ['43.39', '43.3'], ['42.22', '42.2'], ['47.19', '47.1'], ['46.69', '46'],
  ['47.54', '47.54'], ['47.91', '47.91'], ['47.99', '47.99'], ['56.10', '56.10'], ['56.1', '56.10'], [' 96.02 ', '96.02'],
  ['01.11', '01.11'], ['62.01', '62.01'], ['46.1', '46'], ['46', '46'], ['43.29', '43.2'], ['42.91', '42.9'],
  ['85.59', null], ['99.99', null], ['', null], ['47', null],
];

describe('название КВЕД откатом к группе: корпус', () => {
  const results = CORPUS.map(([code, want]) => ({ code, want, got: kvedLookup(map, code)?.code ?? null }));
  const right = results.filter((r) => r.got === r.want).length;
  it(`верно ${right} из ${CORPUS.length}`, () => {
    console.log(`Название КВЕД откатом: верно ${right} из ${CORPUS.length}`);
    expect(results.filter((r) => r.got !== r.want)).toEqual([]);
  });
  it('нормализация как в таблице: нули и точка в конце', () => {
    expect(['56.10', '47.90', '47.', '4720', ' 01.10 '].map(normalizeKved)).toEqual(['56.1', '47.9', '47', '4720', '01.1']);
  });
});
