import { describe, expect, it } from 'vitest';
import { parseUserDate, statusByDays, daysLabel, plural } from './dates';

// Корпус «как мама вводит дату → какая дата». Сегодня — 14.10.2026. Новый промах — сюда.
const CORPUS: [string, string | null][] = [
  ['14.10.2026', '2026-10-14'],
  ['14.10.26', '2026-10-14'],
  ['1.2.2026', '2026-02-01'],
  ['01.02.2026', '2026-02-01'],
  ['14/10/2026', '2026-10-14'],
  ['14-10-2026', '2026-10-14'],
  ['14 10 2026', '2026-10-14'],
  ['14.10', '2026-10-14'],
  ['20.10', '2026-10-20'],
  ['2026-10-14', '2026-10-14'],
  ['14 окт', '2026-10-14'],
  ['14 октября', '2026-10-14'],
  ['14 жовтня', '2026-10-14'],
  ['3 ноября 2026', '2026-11-03'],
  ['31 грудня', '2026-12-31'],
  ['1 січня 2027', '2027-01-01'],
  ['сегодня', '2026-10-14'],
  ['Сьогодні', '2026-10-14'],
  ['завтра', '2026-10-15'],
  ['вчера', '2026-10-13'],
  ['  14.10.2026  ', '2026-10-14'],
  ['14.10.2026 г.', '2026-10-14'],
  ['31.02.2026', null],
  ['32.10.2026', null],
  ['14.13.2026', null],
  ['', null],
  ['абв', null],
  ['14 абв', null],
];

describe('разбор даты: корпус', () => {
  const results = CORPUS.map(([input, want]) => ({ input, want, got: parseUserDate(input), ok: parseUserDate(input) === want }));
  const right = results.filter((r) => r.ok).length;
  it(`верно ${right} из ${CORPUS.length}`, () => {
    console.log(`Разбор даты: верно ${right} из ${CORPUS.length}`);
    expect(results.filter((r) => !r.ok)).toEqual([]);
  });
});

describe('шкала срочности (эталон таблиц п. 10)', () => {
  it('пороги', () => {
    expect([-1, 0, 7, 8, 30, 31].map(statusByDays)).toEqual(['red', 'orange', 'orange', 'yellow', 'yellow', 'green']);
  });
  it('подписи и склонения', () => {
    expect(daysLabel(-24)).toBe('просрочено 24 дн.');
    expect(daysLabel(1)).toBe('завтра');
    expect([1, 2, 5, 11, 21, 22, 25].map((n) => plural(n, 'срок', 'срока', 'сроков'))).toEqual(['срок', 'срока', 'сроков', 'сроков', 'срок', 'срока', 'сроков']);
  });
});
