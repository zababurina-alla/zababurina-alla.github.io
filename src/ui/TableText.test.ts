// Корпус: ведущий эмодзи текста из таблицы → свой значок. Образцы — значения выпадающих списков и тексты сроков таблицы
// (словарь значков, п. 2–3), включая эмодзи с вариантным селектором (☂️, ⚠️) и неизвестный эмодзи (остаётся текстом).
import { describe, expect, it } from 'vitest';
import { splitEmoji } from './TableText';

const CORPUS: [string, string | null, string][] = [
  ['📝 Декларація платника ЄП, III кв.', 'declaration', 'Декларація платника ЄП, III кв.'],
  ['💰 ЄП за жовтень', 'payments', 'ЄП за жовтень'],
  ['☂️ ЄСВ за III квартал', 'esv', 'ЄСВ за III квартал'],
  ['☂ ЄСВ за IV квартал', 'esv', 'ЄСВ за IV квартал'],
  ['🛡 Військовий збір', 'vz', 'Військовий збір'],
  ['✅ Сдано', 'done', 'Сдано'],
  ['✅ Готово', 'done', 'Готово'],
  ['🔄 В работе', 'inProgress', 'В работе'],
  ['⌛ Ждём клиента', 'waiting', 'Ждём клиента'],
  ['⏸ Отложено', 'postponed', 'Отложено'],
  ['🆕 Новое', 'statusNew', 'Новое'],
  ['❌ Не пришло', 'notReceived', 'Не пришло'],
  ['↩️ Возвращено', 'returned', 'Возвращено'],
  ['🔴 Просрочено', 'overdue', 'Просрочено'],
  ['🟠 Горит', 'burning', 'Горит'],
  ['🟡 Скоро', 'soon', 'Скоро'],
  ['🟢 В порядке', 'ok', 'В порядке'],
  ['🔥 Критический', 'critical', 'Критический'],
  ['⚠️ Проверьте КВЕД', 'warning', 'Проверьте КВЕД'],
  ['📞 Позвонить Ромашко', 'call', 'Позвонить Ромашко'],
  ['🔐 Продлить ключ ЭЦП', 'keys', 'Продлить ключ ЭЦП'],
  ['🏦 Монобанк', 'bank', 'Монобанк'],
  ['📱 Дія', 'diia', 'Дія'],
  ['ЄП за жовтень', null, 'ЄП за жовтень'],
  ['🦄 Неизвестное', null, '🦄 Неизвестное'],
  ['Сдано ✅', null, 'Сдано ✅'],
];

describe('ведущий эмодзи из таблицы → свой значок', () => {
  const ok = CORPUS.filter(([t, icon, rest]) => { const r = splitEmoji(t); return r.icon === icon && r.rest === rest; }).length;
  it(`верно ${ok} из ${CORPUS.length}`, () => {
    const wrong = CORPUS.map(([t, icon, rest]) => ({ t, want: [icon, rest], got: splitEmoji(t) }))
      .filter((x) => x.got.icon !== x.want[0] || x.got.rest !== x.want[1]);
    expect(wrong).toEqual([]);
  });
  it('корпус не меньше 20 образцов', () => expect(CORPUS.length).toBeGreaterThanOrEqual(20));
});
