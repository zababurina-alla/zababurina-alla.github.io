// Текст клиента («Оплатила ЄСВ за вересень, 1 902,34»): число не рвётся посреди — пробел между группами разрядов
// становится неразрывным (приёмка-5, Н-9). Суммы сайта (formatMoney) и так с неразрывными пробелами.
export function keepNumbers(text: string): string {
  return text.replace(/(\d)[ \u00A0](?=\d{3}(?!\d))/g, '$1\u00A0');
}
