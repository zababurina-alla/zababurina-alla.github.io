// Корпус показа имён и значений из таблицы: короткое имя в строке и обычный регистр вместо заглавных.
import { describe, expect, it } from 'vitest';
import { shortName, tidyCaps } from './names';

const SHORT: [string, string][] = [
  ['Соловей Тетяна Андріївна', 'Соловей Тетяна'],
  ['Ромашко Олена Петрівна', 'Ромашко Олена'],
  ['ТОВ «Чайка-Сервіс»', 'ТОВ «Чайка-Сервіс»'],
  ['ТОВ Чайка Сервіс Плюс', 'ТОВ Чайка Сервіс Плюс'],
  ['ПП «Бриз»', 'ПП «Бриз»'],
  ['ФГ Колосок', 'ФГ Колосок'],
  ['Товстоног Ігор Петрович', 'Товстоног Ігор'],
  ['Пархоменко Ірина', 'Пархоменко Ірина'],
  ['  Шевчук   Галина  Миколаївна ', 'Шевчук Галина'],
  ['', 'Без имени'],
];
const CAPS: [string, string][] = [
  ['ПРИВАТ БАНК', 'Приват Банк'],
  ['НАЛОГОВЫЙ', 'Налоговый'],
  ['🏛 НАЛОГОВЫЙ', '🏛 Налоговый'],
  ['АЦСК ІДД ДПС', 'АЦСК ІДД ДПС'],
  ['ПриватБанк', 'ПриватБанк'],
  ['Ощадбанк', 'Ощадбанк'],
  ['ДПС', 'ДПС'],
  ['МОНОБАНК', 'Монобанк'],
  ['КНЕДП ДПС', 'КНЕДП ДПС'],
  ['УКРГАЗБАНК', 'Укргазбанк'],
];

describe('показ имён и значений из таблицы', () => {
  const all: [string, string, string][] = [...SHORT.map(([a, b]): [string, string, string] => [a, b, shortName(a)]), ...CAPS.map(([a, b]): [string, string, string] => [a, b, tidyCaps(a)])];
  const ok = all.filter(([, want, got]) => want === got).length;
  it(`верно ${ok} из ${all.length}`, () => {
    expect(all.filter(([, want, got]) => want !== got)).toEqual([]);
    expect(all.length).toBeGreaterThanOrEqual(20);
  });
});
